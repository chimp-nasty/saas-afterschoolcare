INSERT INTO auth.role_permissions (role_id, permission_id)
SELECT r.id, p.id
FROM seed_role_permissions s
JOIN auth.roles r
    ON r.code = s.role_code
JOIN auth.permissions p
    ON p.resource = s.resource
   AND p.action = s.action;

DO $$
DECLARE
    expected INTEGER := (SELECT count(*) FROM seed_role_permissions);
    inserted INTEGER := (SELECT count(*) FROM auth.role_permissions);
BEGIN
    IF inserted <> expected THEN
        RAISE EXCEPTION
            'role_permissions: % rows listed but % inserted; check for unknown roles or permissions',
            expected, inserted;
    END IF;
END
$$;
