"""
Applies the files in migrations/schema, migrations/seed and (in dev)
migrations/dev_seed, in filename order, once each.

- `.sql` files are executed as-is.
- `.py` files must define `up(conn: Connection) -> None`.
- Each file runs in its own transaction and is recorded with a checksum.
  Editing a file that has already been applied is an error: add a new
  file instead (`python -m migrations.migrator new schema add_thing`).
- In dev, `run` and `rebuild` then regenerate app/db/models.py from the
  database with sqlacodegen (requirements-dev.txt), and the frontend's API
  types (frontend/src/lib/api/schema.ts) from the app's OpenAPI document,
  so a schema change reaches both in one step. The API types follow the
  Pydantic schemas, not the database: after an API-only change, run
  `npm run gen:api` (or the `api-types` command below).

Usage:
    python -m migrations.migrator run
    python -m migrations.migrator reset      (dev only)
    python -m migrations.migrator rebuild    (dev only)
    python -m migrations.migrator models     (regenerate models only)
    python -m migrations.migrator api-types  (regenerate frontend API types only)
    python -m migrations.migrator new <folder> <name>
"""

import hashlib
import importlib.util
import os
import shutil
import subprocess
import sys
from pathlib import Path

from dotenv import load_dotenv
from sqlalchemy import MetaData, create_engine, text
from sqlalchemy.engine import Connection, Engine

from app.core.config import settings


load_dotenv()


MIGRATIONS_DIR = Path(__file__).parent

MIGRATION_SCHEMA = "migrations"
MIGRATION_TABLE = f"{MIGRATION_SCHEMA}.migration_history"

ALWAYS_FOLDERS = ("schema", "seed")
DEV_FOLDERS = ("dev_seed",)

# Environments whose database may be reset and gets dev seed data. The
# test suite (APP_ENV=test) rebuilds its own database on every run.
DISPOSABLE_ENVS = ("dev", "test")

BACKEND_DIR = MIGRATIONS_DIR.parent
FRONTEND_DIR = BACKEND_DIR.parent / "frontend"

# Written for the frontend's `gen:api:file` script (gitignored).
OPENAPI_FILE = FRONTEND_DIR / ".openapi.json"

MODEL_SCHEMAS = ("tenancy", "auth", "public")
MODELS_FILE = MIGRATIONS_DIR.parent / "app" / "db" / "models.py"
MODELS_HEADER = (
    "# GENERATED by `python -m migrations.migrator models` from the database.\n"
    "# Do not edit: change the schema with a migration and regenerate.\n\n"
)


def get_engine() -> Engine:
    database_admin_url = os.environ.get(
        "DATABASE_ADMIN_URL"
    )

    if not database_admin_url:
        raise RuntimeError(
            "DATABASE_ADMIN_URL environment variable is required."
        )

    return create_engine(
        database_admin_url,
        pool_pre_ping=True,
    )


def get_runtime_password() -> str:
    # Consumed by schema/*_runtime_role.sql via current_setting().
    password = os.environ.get("APP_DB_PASSWORD")

    if not password:
        raise RuntimeError(
            "APP_DB_PASSWORD environment variable is required. "
            "It must match the app_user password in DATABASE_URL."
        )

    return password


def ensure_migration_table(engine: Engine) -> None:
    with engine.begin() as conn:
        conn.execute(
            text(
                f"""
                CREATE SCHEMA IF NOT EXISTS {MIGRATION_SCHEMA};

                CREATE TABLE IF NOT EXISTS {MIGRATION_TABLE} (
                    id SERIAL PRIMARY KEY,
                    migration_name VARCHAR(255) NOT NULL UNIQUE,
                    checksum CHAR(64) NOT NULL,
                    applied_at TIMESTAMPTZ NOT NULL
                        DEFAULT CURRENT_TIMESTAMP
                );
                """
            )
        )


def get_applied(engine: Engine) -> dict[str, str]:
    with engine.connect() as conn:
        rows = conn.execute(
            text(
                f"SELECT migration_name, checksum FROM {MIGRATION_TABLE};"
            )
        )

        return {
            row.migration_name: row.checksum
            for row in rows
        }


def list_files(folder: str) -> list[Path]:
    directory = MIGRATIONS_DIR / folder

    if not directory.is_dir():
        return []

    return sorted(
        path
        for path in directory.iterdir()
        if path.suffix in (".sql", ".py")
        and not path.name.startswith("__")
    )


def checksum(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def apply_file(conn: Connection, path: Path) -> None:
    if path.suffix == ".sql":
        # Raw DBAPI cursor: no bind-parameter parsing, so `:name` and `%`
        # in the SQL are passed through untouched.
        with conn.connection.cursor() as cursor:
            cursor.execute(path.read_text(encoding="utf-8"))

        return

    spec = importlib.util.spec_from_file_location(
        f"migrations._{path.parent.name}_{path.stem}",
        path,
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)

    module.up(conn)


def run() -> list[str]:
    engine = get_engine()
    runtime_password = get_runtime_password()

    ensure_migration_table(engine)
    applied = get_applied(engine)

    folders = ALWAYS_FOLDERS + (
        DEV_FOLDERS if settings.APP_ENV in DISPOSABLE_ENVS else ()
    )

    newly_applied: list[str] = []

    for folder in folders:
        for path in list_files(folder):
            name = f"{folder}/{path.name}"
            file_checksum = checksum(path)

            if name in applied:
                if applied[name] != file_checksum:
                    raise RuntimeError(
                        f"{name} was edited after being applied. "
                        "Revert it and add a new migration file instead "
                        "(or `rebuild` in dev)."
                    )

                continue

            print(f"Applying {name}")

            with engine.begin() as conn:
                conn.execute(
                    text(
                        "SELECT set_config("
                        "'app.runtime_password', :password, true)"
                    ),
                    {"password": runtime_password},
                )

                apply_file(conn, path)

                conn.execute(
                    text(
                        f"""
                        INSERT INTO {MIGRATION_TABLE}
                            (migration_name, checksum)
                        VALUES (:name, :checksum);
                        """
                    ),
                    {
                        "name": name,
                        "checksum": file_checksum,
                    },
                )

            newly_applied.append(name)

    if not newly_applied:
        print("Database is up to date.")

    if settings.APP_ENV == "dev":
        generate_models(engine)
        generate_api_types()

    return newly_applied


def generate_models(engine: Engine | None = None) -> bool:
    try:
        from sqlacodegen.generators import DeclarativeGenerator
    except ImportError:
        print(
            "Skipping model generation: sqlacodegen is not installed "
            "(pip install -r requirements-dev.txt)."
        )
        return False

    engine = engine or get_engine()

    metadata = MetaData()

    for schema in MODEL_SCHEMAS:
        metadata.reflect(engine, schema=schema)

    # use_inflect: singular class names (bookings -> Booking).
    # nojoined: child_medical_state's PK is also an FK to child_profile;
    # without this it's generated as a subclass of ChildProfile.
    source = DeclarativeGenerator(
        metadata,
        engine,
        ["use_inflect", "nojoined"],
    ).generate()

    # Repositories write their joins explicitly, so relationships (one per
    # line) are dropped to keep the models to plain columns.
    source = "\n".join(
        line.replace(", relationship", "")
        for line in source.splitlines()
        if "relationship(" not in line
    )

    source = MODELS_HEADER + source.rstrip() + "\n"

    if (
        MODELS_FILE.exists()
        and MODELS_FILE.read_text(encoding="utf-8") == source
    ):
        print("Models unchanged.")
        return False

    MODELS_FILE.write_text(source, encoding="utf-8")
    print(f"Models updated: {MODELS_FILE.relative_to(MIGRATIONS_DIR.parent)}")

    return True


def generate_api_types() -> bool:
    """
    Regenerate frontend/src/lib/api/schema.ts without the backend running:
    build the OpenAPI document from the app, then run the frontend's
    `gen:api:file` script on it. Skipped (with a message) if either step
    can't run, like model generation without sqlacodegen.
    """
    # A fresh interpreter, so the app imports the models.py just written.
    exported = subprocess.run(
        [
            sys.executable,
            "-c",
            "import json, sys; from app.main import app; json.dump(app.openapi(), sys.stdout)",
        ],
        cwd=BACKEND_DIR,
        capture_output=True,
        text=True,
    )

    if exported.returncode != 0:
        # The last line of the traceback says what went wrong.
        reason = exported.stderr.strip().splitlines()[-1:]

        print(
            "Skipping API types: the app's OpenAPI document couldn't be built."
            + (f"\n{reason[0]}" if reason else "")
        )
        return False

    npm = shutil.which("npm")

    if not npm or not FRONTEND_DIR.exists():
        print("Skipping API types: npm or the frontend folder wasn't found.")
        return False

    OPENAPI_FILE.write_text(exported.stdout, encoding="utf-8")

    generated = subprocess.run(
        [npm, "run", "--silent", "gen:api:file"],
        cwd=FRONTEND_DIR,
    )

    if generated.returncode != 0:
        print("Skipping API types: `npm run gen:api:file` failed.")
        return False

    print("API types updated: frontend/src/lib/api/schema.ts")

    return True


def reset() -> None:
    if settings.APP_ENV not in DISPOSABLE_ENVS:
        raise RuntimeError(
            "Database reset is only permitted "
            f"when APP_ENV is one of {DISPOSABLE_ENVS}."
        )

    engine = get_engine()

    with engine.begin() as conn:
        conn.execute(
            text(
                """
                DROP SCHEMA IF EXISTS public CASCADE;
                DROP SCHEMA IF EXISTS auth CASCADE;
                DROP SCHEMA IF EXISTS tenancy CASCADE;
                DROP SCHEMA IF EXISTS migrations CASCADE;

                CREATE SCHEMA public;
                """
            )
        )

    print("Database reset completed.")


def rebuild() -> list[str]:
    reset()
    return run()


def new(folder: str, name: str) -> Path:
    if folder not in ALWAYS_FOLDERS + DEV_FOLDERS:
        raise ValueError(
            f"Unknown folder '{folder}'. "
            f"Use one of: {', '.join(ALWAYS_FOLDERS + DEV_FOLDERS)}"
        )

    existing = list_files(folder)
    next_number = (
        max(int(path.name[:4]) for path in existing) + 1
        if existing
        else 1
    )

    path = (
        MIGRATIONS_DIR
        / folder
        / f"{next_number:04d}_{name}.sql"
    )
    path.write_text(f"-- {path.name}\n\n", encoding="utf-8")

    print(f"Created {path.relative_to(MIGRATIONS_DIR.parent)}")

    return path


def main() -> None:
    command = (
        sys.argv[1].lower()
        if len(sys.argv) > 1
        else "run"
    )

    if command == "run":
        run()
        return

    if command == "reset":
        reset()
        return

    if command == "rebuild":
        rebuild()
        return

    if command == "models":
        generate_models()
        return

    if command == "api-types":
        generate_api_types()
        return

    if command == "new" and len(sys.argv) == 4:
        new(sys.argv[2], sys.argv[3])
        return

    raise ValueError(
        f"Unknown migration command: {' '.join(sys.argv[1:])}"
    )


if __name__ == "__main__":
    main()
